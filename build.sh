#!/bin/sh
# Write scripts/catalog.js from the converter's build/*.json and check that
# the version numbers agree. Run tools/convert.py first to (re)make structures.
cd "$(dirname "$0")" || exit 1
python3 - <<'PY' || exit 1
import glob, json, re, sys, os
bp = json.load(open("behavior_pack/manifest.json"))
v = bp["header"]["version"]; s = ".".join(map(str, v))
js = re.search(r'^export const VERSION = "(.*)";', open("behavior_pack/scripts/main.js").read(), re.M).group(1)
bad = [k for k, ok in {
    "module versions": all(m["version"] == v for m in bp["modules"]),
    "pack name": bp["header"]["name"] == f"Better Structures {s}",
    "VERSION in main.js": js == s,
}.items() if not ok]
if bad:
    sys.exit(f"version {s} mismatch: " + ", ".join(bad))
cat = {}
for f in sorted(glob.glob("build/*.json")):
    if f.endswith(".pools.json"):
        continue
    for name, info in json.load(open(f))["structures"].items():
        if not os.path.exists(f"behavior_pack/structures/bs/{name}.mcstructure"):
            sys.exit(f"{name} is in {f} but has no .mcstructure; rerun tools/convert.py")
        cat[name] = info["size"]
open("behavior_pack/scripts/catalog.js", "w").write(
    "// Generated by build.sh from build/*.json. Name -> [x, y, z] size.\nexport const CATALOG = "
    + json.dumps(cat, separators=(",", ":")) + ";\n")

# Jigsaw data for the assembler: pools, sites and the pieces they can reach.
sys.path.insert(0, "tools")
import nbt, collections
SITE_GROUPS = ["plains"]  # ruins sites wait on terrain-draped pieces that need rotated block states
info, pools, sites = {}, {}, {}
for f in sorted(glob.glob("build/*.json")):
    d = json.load(open(f))
    if f.endswith(".pools.json"):
        pools.update(d["pools"])
        sites.update({k: v for k, v in d["sites"].items() if k.split(":")[0] in SITE_GROUPS})
    else:
        info.update(d["structures"])
used, proj, todo = {}, collections.defaultdict(set), [v["start_pool"] for v in sites.values()]
while todo:
    pid = todo.pop()
    if pid in used or pid not in pools:
        continue
    used[pid] = pools[pid]
    todo.append(pools[pid]["fallback"])
    for w, piece, pr in pools[pid]["elements"]:
        if piece:
            proj[piece].add(pr)
            todo += [j["pool"] for j in info[piece]["jigsaws"]]

def js_states(states):
    return {k: (bool(v.v) if v.t == nbt.BYTE else v.v) if isinstance(v, nbt.Tag) else v for k, v in states.items()}

# A tiny marker structure the script uses to learn how the game rotates structures.
from nbt import I, Lst
V = (1 << 24) | (26 << 16) | (60 << 8)
cpal = [{"name": "minecraft:" + n, "states": {}, "version": I(V)} for n in ("air", "gold_block", "iron_block", "diamond_block")]
ccells = [0] * 6  # 3 x 1 x 2, index = x * 2 + z
ccells[0], ccells[4], ccells[1] = 1, 2, 3  # gold at 0,0,0; iron at 2,0,0; diamond at 0,0,1
nbt.dump({"format_version": I(1), "size": Lst(nbt.INT, [I(3), I(1), I(2)]),
          "structure": {"block_indices": Lst(nbt.LIST, [Lst(nbt.INT, [I(c) for c in ccells]), Lst(nbt.INT, [I(-1)] * 6)]),
                        "entities": Lst(nbt.COMPOUND, []),
                        "palette": {"default": {"block_palette": Lst(nbt.COMPOUND, cpal), "block_position_data": {}}}},
          "structure_world_origin": Lst(nbt.INT, [I(0), I(0), I(0)])}, "behavior_pack/structures/bs/calib.mcstructure")

pieces = {}
for name, kinds in sorted(proj.items()):
    st = nbt.load(f"behavior_pack/structures/bs/{name}.mcstructure", little=True, typed=True)
    # Typed lists come back wrapped, so unwrap with .v.
    sx, sy, sz = [t.v for t in st["size"].v]
    cells = [t.v for t in st["structure"]["block_indices"].v[0].v]
    pal = st["structure"]["palette"]["default"]["block_palette"].v
    solid = lambda i: i >= 0 and pal[i]["name"] != "minecraft:air"
    p = {"s": [sx, sy, sz], "j": [
        {"p": j["pos"], "f": j["orientation"].split("_")[0], "u": j["orientation"].split("_")[1],
         "n": j["name"], "t": j["target"], "pool": j["pool"], "roll": j.get("joint") != "aligned"}
        for j in info[name]["jigsaws"]]}
    if "t" in kinds:
        flat = []
        for x in range(sx):
            for y in range(sy):
                for z in range(sz):
                    i = cells[(x * sy + y) * sz + z]
                    if i >= 0:
                        flat += [x, y, z, i]
        p["tm"] = {"pal": [[e["name"], js_states(e["states"])] for e in pal], "b": flat}
    if "r" in kinds:
        base = [cells[(x * sy) * sz + z] for x in range(sx) for z in range(sz)]
        p["base"] = "".join("1" if solid(i) else "0" for i in base)
        common = collections.Counter(pal[i]["name"] for i in base if solid(i)).most_common(1)
        p["fb"] = common[0][0] if common else "minecraft:cobblestone"
    pieces[name] = p
out = {"PIECES": pieces,
       "POOLS": {k: {"fb": v["fallback"], "e": v["elements"]} for k, v in used.items()},
       "SITES": sites}
open("behavior_pack/scripts/data.js", "w").write(
    "// Generated by build.sh from build/*.pools.json and the converted structures.\n"
    + "".join(f"export const {k} = {json.dumps(v, separators=(',', ':'))};\n" for k, v in out.items()))
print(f"Better Structures {s}: {len(cat)} structures in the catalog, {len(sites)} sites, {len(used)} pools, {len(pieces)} jigsaw pieces")
PY
rm -f BetterStructures.mcaddon && zip -qrX BetterStructures.mcaddon behavior_pack -x '*.DS_Store' && echo "built BetterStructures.mcaddon"
